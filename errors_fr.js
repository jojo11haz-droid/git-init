export function frError(message) {
  if (typeof message !== 'string' || !message) return message;
  if (Object.prototype.hasOwnProperty.call(FR, message)) return FR[message];
  for (const [shape, say] of PATTERNS) {
    const m = message.match(shape);
    if (m) return say(m);
  }
  return message;
}

export function hasFrError(message) {
  return frError(message) !== message;
}

// Express middleware: for a French page or app, answer errors in French.
export function localizeErrors(req, res, next) {
  if (String(req.get('X-Btw-Lang') || '').toLowerCase() !== 'fr') return next();
  const send = res.json.bind(res);
  res.json = (body) => {
    if (body && typeof body === 'object' && !Array.isArray(body) && typeof body.error === 'string') {
      body = { ...body, error: frError(body.error) };
    }
    return send(body);
  };
  next();
}
